/**
 * 업무일(공장이 하루로 보는 단위) — 화면 쪽 규칙
 *
 * 덕우전자의 하루는 자정이 아니라 오전 8시 교대로 끊깁니다.
 * 기간 조회는 **시작일 08:00 부터 종료일 08:00 까지**입니다.
 * 구간을 정하는 것은 서버(API `BusinessDay`)이고, 화면은 날짜만 보냅니다.
 *
 *   기간 09-01 ~ 09-16  → 09-01 08:00 ~ 09-16 08:00
 *   날짜 하나(일일 보고) → 그 전날 08:00 ~ 당일 08:00
 *
 * 안내가 없으면 "자정 기준으로 세었을 때와 숫자가 다르다"는 문의가 생깁니다.
 * 날짜·기간으로 조회하는 화면에는 이 문구를 같이 두세요.
 *
 * 적용 화면 — 생산실적 · 불량현황 · AOI(외관/치수/시리얼) · 공정 대시보드 ·
 * AI 통합 대시보드 · 지표값.
 * 감사 로그 · 다운로드 이력 · 알림 발송 이력 · 동기화 이력 · AI 질의 이력과
 * 실시간 모니터링은 자정 기준 그대로입니다 (2026-09-16 결정).
 */
import { shiftDate } from '@shared/utils/formatUtil';

export const BUSINESS_DAY_NOTE =
  '공장 교대에 맞춰 하루는 오전 8시에 시작합니다 — 조회 구간은 시작일 08:00 부터 종료일 08:00 까지입니다.';

/**
 * 시작일과 종료일이 같으면 시작일을 하루 앞당깁니다.
 *
 * 같은 날이면 구간이 `08:00 ~ 08:00` 이 되어 결과가 0건입니다. 서버도 같은 보정을
 * 하지만, 화면이 먼저 날짜를 바꿔 줘야 **사용자가 실제 조회 구간을 눈으로 봅니다.**
 * 조용히 서버에서만 넓히면 "하루를 골랐는데 왜 전날 자료가 나오냐"가 됩니다.
 *
 * 날짜를 바꾸는 모든 입력(시작일·종료일·빠른 기간)에서 함께 부르세요.
 */
export function normalizeRange(from, to) {
  if (!from || !to || from !== to) return { from, to };
  return { from: shiftDate(to, -1), to };
}
