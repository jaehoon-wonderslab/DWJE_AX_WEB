 const input=[{_children:[{_children:[parent]}]}],before=JSON.stringify(input);
 const output=compactDefectTree(input)[0]._children[0]._children[0];
 assert.equal(output.wcNm,'공정 A');assert.equal(output.plantNm,'공장 A');
